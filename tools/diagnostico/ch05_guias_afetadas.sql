PROMPT == guias com nota cancelada na competencia e valor diferente da soma das notas
SELECT g.SITUACAO, COUNT(*) AS GUIAS, COUNT(DISTINCT g.PRESTADOR_ID) AS CONTRIBUINTES,
       SUM(g.VALOR_ISS - s.VALOR) AS COBRADO_A_MAIS, MIN(g.COMPETENCIA) AS DESDE, MAX(g.COMPETENCIA) AS ATE
  FROM GUIAS g
  JOIN (SELECT n.PRESTADOR_ID, n.COMPETENCIA,
               NVL(SUM(CASE WHEN n.SITUACAO = 'N' AND n.ISS_RETIDO = 'N'
                            THEN ROUND((n.VALOR_SERVICOS - n.VALOR_DEDUCOES) * n.ALIQUOTA, 2) END), 0) AS VALOR,
               MAX(CASE WHEN n.SITUACAO = 'C' THEN 1 ELSE 0 END) AS TEM_CANCELADA
          FROM NFSE n
         GROUP BY n.PRESTADOR_ID, n.COMPETENCIA) s
    ON s.PRESTADOR_ID = g.PRESTADOR_ID AND s.COMPETENCIA = g.COMPETENCIA
 WHERE s.TEM_CANCELADA = 1
   AND g.VALOR_ISS <> s.VALOR
 GROUP BY g.SITUACAO;

EXIT
