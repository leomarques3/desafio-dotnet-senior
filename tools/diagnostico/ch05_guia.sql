SET LINES 200 PAGES 100 FEEDBACK OFF VERIFY OFF
COLUMN situacao FORMAT A8
ALTER SESSION SET NLS_DATE_FORMAT = 'YYYY-MM-DD HH24:MI:SS';

PROMPT == guia da competencia atual
SELECT g.VALOR_ISS AS GUIA, g.SITUACAO, g.DT_ATUALIZACAO,
       (SELECT NVL(SUM(ROUND((n.VALOR_SERVICOS - n.VALOR_DEDUCOES) * n.ALIQUOTA, 2)), 0)
          FROM NFSE n
         WHERE n.PRESTADOR_ID = g.PRESTADOR_ID AND n.COMPETENCIA = g.COMPETENCIA
           AND n.SITUACAO = 'N' AND n.ISS_RETIDO = 'N') AS ESPERADO
  FROM GUIAS g JOIN CONTRIBUINTES c ON c.ID = g.PRESTADOR_ID
 WHERE c.INSCRICAO_MUNICIPAL = '&1' AND g.COMPETENCIA = TRUNC(SYSDATE, 'MM');

PROMPT == notas da competencia atual
SELECT n.NUMERO, n.SITUACAO, n.ISS_RETIDO, n.VALOR_ISS, n.DT_CANCELAMENTO
  FROM NFSE n JOIN CONTRIBUINTES c ON c.ID = n.PRESTADOR_ID
 WHERE c.INSCRICAO_MUNICIPAL = '&1' AND n.COMPETENCIA = TRUNC(SYSDATE, 'MM')
 ORDER BY n.NUMERO;

EXIT
