PROMPT == guia x soma do ISS das notas
SELECT g.COMPETENCIA, g.SITUACAO, g.VALOR_ISS AS GUIA,
       (SELECT NVL(SUM(n.VALOR_ISS), 0)
          FROM NFSE n
         WHERE n.PRESTADOR_ID = g.PRESTADOR_ID AND n.COMPETENCIA = g.COMPETENCIA
           AND n.SITUACAO = 'N' AND n.ISS_RETIDO = 'N') AS SOMA_NOTAS
  FROM GUIAS g JOIN CONTRIBUINTES c ON c.ID = g.PRESTADOR_ID
 WHERE c.INSCRICAO_MUNICIPAL = '&1' AND g.COMPETENCIA = TO_DATE('&2', 'YYYY-MM');

PROMPT == notas com ISS diferente de ROUND(base x aliquota, 2)
SELECT n.NUMERO, n.DT_EMISSAO, n.BASE_CALCULO, n.ALIQUOTA, n.VALOR_ISS AS ISS_NOTA,
       ROUND(n.BASE_CALCULO * n.ALIQUOTA, 2) AS ISS_ROUND
  FROM NFSE n JOIN CONTRIBUINTES c ON c.ID = n.PRESTADOR_ID
 WHERE c.INSCRICAO_MUNICIPAL = '&1' AND n.COMPETENCIA = TO_DATE('&2', 'YYYY-MM')
   AND n.VALOR_ISS <> ROUND(n.BASE_CALCULO * n.ALIQUOTA, 2)
 ORDER BY n.NUMERO;

