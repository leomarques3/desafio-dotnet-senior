PROMPT == notas com ISS diferente de ROUND(base x aliquota, 2)
SELECT COUNT(*) AS NOTAS, COUNT(DISTINCT PRESTADOR_ID) AS CONTRIBUINTES,
       SUM(ROUND(BASE_CALCULO * ALIQUOTA, 2) - VALOR_ISS) AS DIFERENCA,
       MIN(DT_EMISSAO) AS PRIMEIRA, MAX(DT_EMISSAO) AS ULTIMA
  FROM NFSE
 WHERE VALOR_ISS <> ROUND(BASE_CALCULO * ALIQUOTA, 2);

PROMPT == guias diferentes da soma do ISS das notas, por situacao
SELECT g.SITUACAO, COUNT(*) AS GUIAS, COUNT(DISTINCT g.PRESTADOR_ID) AS CONTRIBUINTES,
       SUM(g.VALOR_ISS - NVL(s.ISS_NOTAS, 0)) AS COBRADO_A_MAIS, MIN(g.COMPETENCIA) AS DESDE, MAX(g.COMPETENCIA) AS ATE
  FROM GUIAS g
  LEFT JOIN (SELECT PRESTADOR_ID, COMPETENCIA, SUM(VALOR_ISS) AS ISS_NOTAS
               FROM NFSE
              WHERE SITUACAO = 'N' AND ISS_RETIDO = 'N'
              GROUP BY PRESTADOR_ID, COMPETENCIA) s
    ON s.PRESTADOR_ID = g.PRESTADOR_ID AND s.COMPETENCIA = g.COMPETENCIA
 WHERE g.VALOR_ISS <> NVL(s.ISS_NOTAS, 0)
 GROUP BY g.SITUACAO;

PROMPT == guias pagas diferentes da soma (para a fiscalizacao)
SELECT c.INSCRICAO_MUNICIPAL, g.COMPETENCIA, g.VALOR_ISS AS GUIA, NVL(s.ISS_NOTAS, 0) AS SOMA_NOTAS,
       g.VALOR_ISS - NVL(s.ISS_NOTAS, 0) AS PAGO_A_MAIS
  FROM GUIAS g
  JOIN CONTRIBUINTES c ON c.ID = g.PRESTADOR_ID
  LEFT JOIN (SELECT PRESTADOR_ID, COMPETENCIA, SUM(VALOR_ISS) AS ISS_NOTAS
               FROM NFSE
              WHERE SITUACAO = 'N' AND ISS_RETIDO = 'N'
              GROUP BY PRESTADOR_ID, COMPETENCIA) s
    ON s.PRESTADOR_ID = g.PRESTADOR_ID AND s.COMPETENCIA = g.COMPETENCIA
 WHERE g.SITUACAO = 'P' AND g.VALOR_ISS <> NVL(s.ISS_NOTAS, 0)
 ORDER BY g.COMPETENCIA, c.INSCRICAO_MUNICIPAL;

