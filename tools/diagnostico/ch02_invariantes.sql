SET LINES 200 PAGES 100 FEEDBACK OFF
COLUMN serie FORMAT A8

PROMPT == RPS gravados mais de uma vez
SELECT r.PRESTADOR_ID, r.SERIE, COUNT(*) AS RPS_REPETIDOS
  FROM (SELECT PRESTADOR_ID, SERIE, NUMERO FROM RPS GROUP BY PRESTADOR_ID, SERIE, NUMERO HAVING COUNT(*) > 1) r
 GROUP BY r.PRESTADOR_ID, r.SERIE;

PROMPT == prestadores com lacuna ou numero repetido na numeracao da NFS-e
SELECT PRESTADOR_ID, COUNT(*) AS NOTAS, MAX(NUMERO) AS MAIOR_NUMERO, COUNT(DISTINCT NUMERO) AS NUMEROS_DISTINTOS
  FROM NFSE
 GROUP BY PRESTADOR_ID
HAVING COUNT(*) <> MAX(NUMERO) OR COUNT(*) <> COUNT(DISTINCT NUMERO);

PROMPT == lotes do fechamento: situacao, RPS informados, notas geradas e erros gravados
SELECT l.PROTOCOLO, l.SITUACAO, l.QTD_RPS,
       (SELECT COUNT(*) FROM RPS r WHERE r.PROTOCOLO = l.PROTOCOLO AND r.NFSE_ID IS NOT NULL) AS NOTAS,
       (LENGTH(l.ERROS) - LENGTH(REPLACE(l.ERROS, '<MensagemRetorno>'))) / LENGTH('<MensagemRetorno>') AS ERROS
  FROM LOTES_RPS l
 WHERE l.DT_RECEBIMENTO > SYSDATE - 1/24 AND l.PRESTADOR_ID < 100000
 ORDER BY l.PROTOCOLO;

