SET DEFINE OFF
WHENEVER SQLERROR EXIT FAILURE

DECLARE
    v_existe NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_existe FROM USER_TABLES WHERE TABLE_NAME = 'AJUSTE_GUIA_CH05';
    IF v_existe = 1 THEN
        EXECUTE IMMEDIATE 'UPDATE GUIAS g SET g.VALOR_ISS = (SELECT a.VALOR_ANTES FROM AJUSTE_GUIA_CH05 a WHERE a.GUIA_ID = g.ID ' ||
                          'ORDER BY a.DT_AJUSTE FETCH FIRST 1 ROW ONLY) ' ||
                          'WHERE g.ID IN (SELECT GUIA_ID FROM AJUSTE_GUIA_CH05) AND g.SITUACAO = ''A''';
        COMMIT;
        EXECUTE IMMEDIATE 'DROP TABLE AJUSTE_GUIA_CH05 PURGE';
    END IF;
END;
/

EXIT
