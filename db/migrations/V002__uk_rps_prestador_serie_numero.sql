SET DEFINE OFF
WHENEVER SQLERROR EXIT FAILURE

ALTER SESSION SET DDL_LOCK_TIMEOUT = 30;

DECLARE
    v_existe NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_existe FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME = 'UK_RPS_PREST_SERIE_NUM';
    IF v_existe = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE RPS ADD CONSTRAINT UK_RPS_PREST_SERIE_NUM UNIQUE (PRESTADOR_ID, SERIE, NUMERO) ' ||
                          'USING INDEX IX_RPS_PRESTADOR_NUM ENABLE NOVALIDATE';
    END IF;
END;
/

EXIT
