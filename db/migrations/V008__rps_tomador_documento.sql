SET DEFINE OFF
WHENEVER SQLERROR EXIT FAILURE

ALTER SESSION SET DDL_LOCK_TIMEOUT = 30;

DECLARE
    v_existe NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_existe FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'RPS' AND COLUMN_NAME = 'TOMADOR_DOCUMENTO';
    IF v_existe = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE RPS ADD (TOMADOR_DOCUMENTO VARCHAR2(14))';
    END IF;
END;
/

EXIT
